// 随机获取指定情绪的N条建议
export function getRandomAdvice(emotion, count = 5) {
  const adviceList = emotionAdviceLibrary[emotion] || []
  const shuffled = [...adviceList].sort(() => 0.5 - Math.random())
  return shuffled.slice(0, count)
}

// 按分类获取建议
export function getAdviceByCategory(emotion, category) {
  const adviceList = emotionAdviceLibrary[emotion] || []
  return adviceList.filter(advice => advice.category === category)
}

// 获取所有分类
export function getAllCategories(emotion) {
  const adviceList = emotionAdviceLibrary[emotion] || []
  return [...new Set(adviceList.map(advice => advice.category))]
}

